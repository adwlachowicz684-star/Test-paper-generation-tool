# -*- coding: utf-8 -*-
"""考试类型：题目标签 + 组卷用途

## 一个枚举，两种用法

    EXAMS —— 打在**题目**上，多值（一道题可同时适合月考和期中）
    USES  —— 标记**本次组卷**的用途，印在卷头上

两者共用同一套枚举值，但语义完全不同，不能混为一谈：

    题目标签：这道题以前在哪些场合考过 / 适合哪些场合
    组卷用途：我现在要出一份什么卷子

## 为什么「全部」不是枚举里的值

「全部」= 不加这个筛选条件，不是一个能打在题目上的标签。
塞进枚举的话就会出现「某道题属于全部考试」这种无意义的数据。
所以枚举里只有 6 个真值，「全部」是界面上的清空态。

## 数据现状

题库 463 道题**全部没有**这个字段 —— 考试类型无法从题目内容推断
（同一道题既可用于周考也可用于期中），自动标注必然出错。
所以：
  - 题目侧：字段预留（q['exams'] = []），等人工或批量标注入口补
  - 筛选侧：不做数据迁移，留空时所有题目的 exams 都是空数组

**空数组意味着「未标注」，而不是「不属于任何考试」**。
筛选时必须注意：勾了「月考」，未标注的题会被全部筛掉。
这是符合直觉的（我要出月考卷，当然只要标了月考的题），
但用户第一次用会看到「候选 0」，所以前端要显示题数提示。
"""

# 9 个真值。顺序 = **考查范围从小到大**：
#   知识点测验（单个考点）→ 单元测试（一章）→ 周考 → 月考
#   → 期中 → 期末 → 模考 → 真题
# 学情考察不是"范围"而是"目的"（摸底诊断），放最后，
# 与 USES 里的「综合练习」同属目的类，不该插在范围序列中间。
EXAMS = ['知识点测验', '单元测试', '周考', '月考',
         '期中', '期末', '模考', '真题', '学情考察']

# 卷头用途：比题目标签多一个「综合练习」
# （没选任何类型、或选了多个时的卷头称呼）
USES = EXAMS + ['综合练习']

ALL = '全部'          # 仅界面用，不入库
UNLABELED = '未标注'   # 题数统计时显示，不入库


def norm(value):
    """把任意写法归一到枚举值。

    兼容历史数据可能写错的情况（空格、繁体、别名）。
    认不出返回 '' —— 调用方决定是丢弃还是报警。
    """
    v = str(value or '').strip()
    if not v or v == ALL or v == UNLABELED:
        return ''
    for e in EXAMS:
        if v == e:
            return e
    # 常见别名。
    # 主要防导入数据时的写法差异 —— 不归一的话，
    # 「章节测试」和「单元测试」会变成两个不同的值，
    # 筛选时互相看不见，表现为"明明标了却筛不出来"。
    alias = {
        '期中考试': '期中', '期末考试': '期末',
        '模拟考': '模考', '模拟': '模考', '模拟考试': '模考',
        '高考真题': '真题', '历年真题': '真题', '真题演练': '真题',
        '周练': '周考', '周测': '周考', '月测': '月考',
        # 新增三类
        '章节测试': '单元测试', '单元测': '单元测试',
        '章节测验': '单元测试', '单元过关': '单元测试',
        '考点测验': '知识点测验', '专项测验': '知识点测验',
        '随堂测': '知识点测验', '小测': '知识点测验',
        '学情': '学情考察', '学情检测': '学情考察',
        '摸底考': '学情考察', '摸底测试': '学情考察',
        '诊断性测试': '学情考察',
    }
    return alias.get(v, '')


def of_question(q):
    """取一道题的考试类型列表（已归一，去重）"""
    raw = q.get('exams')
    if isinstance(raw, str):
        raw = [x for x in raw.replace('，', ',').split(',')]
    out, seen = [], set()
    for x in (raw or []):
        e = norm(x)
        if e and e not in seen:
            seen.add(e)
            out.append(e)
    return out


def use_of(picked):
    """由筛选时勾中的类型推出卷头用途。

    只勾一个 → 就是它（「月考」→ 月考卷）
    勾多个   → 「综合练习」（一道题跨多个场合时，
                说它是「月考卷」是骗人的）
    没勾     → 「综合练习」（不限类型 = 综合）
    """
    ps = [norm(x) for x in (picked or [])]
    ps = [x for x in ps if x]
    if len(ps) == 1:
        return ps[0]
    return '综合练习'
