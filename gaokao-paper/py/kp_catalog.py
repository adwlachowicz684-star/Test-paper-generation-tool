# ---------- 题型节点（三级是实体，不只是字符串）----------
"""
设计要点
--------
题型是**独立实体**，有全局唯一 ID，而不是挂在某处的字符串。

一个题型节点记录：
    id        全局唯一（如 M-T-137）
    name      题型名
    primary   (一级, 二级)  主归属，唯一
    cross     [一级, ...]   交叉归属（可多个），这就是「多父」
    questions [题目ID, ...] 挂在此题型下的题目

双向索引：
    题目 → 题型：存在 bank.json 的 q['topics'] 里（**唯一权威来源**）
    题型 → 题目：运行时从题库反建（_rebuild_qindex）

为什么只存单向：双写必然不一致。题目上的标签是权威，
反索引每次从题库重建，代价是 O(n) 扫描，216 题可忽略。
"""
SUBJ_CODE = {"数学": "M", "物理": "P", "化学": "C",
             "生物": "B", "语文": "Y", "英语": "E"}


def _build_topics():
    """从 CATALOG + TOPIC_XREF 构建题型节点表。

    ID 规则：{科目码}-T-{三位序号}，按 (一级, 二级, 题型) 遍历顺序分配。
    只要目录不变，ID 就稳定 —— 这点很重要，因为 ID 会被存进题目里。

    交叉题型**不新占 ID**：复用主归属那个节点，只是在 cross 里多记一条。
    """
    nodes, seq = {}, {}
    for subj, pairs in CATALOG.items():
        code = SUBJ_CODE.get(subj, "X")
        n = 0
        for l1, subs in pairs:
            if not isinstance(subs, dict):
                continue
            for l2, tops in subs.items():
                if l2 == XSECTION:
                    continue          # 挂载点不是真实出处，跳过
                for t in tops or []:
                    n += 1
                    tid = "%s-T-%03d" % (code, n)
                    nodes[tid] = {
                        "id": tid, "name": t, "subject": subj,
                        "primary": (l1, l2),
                        "cross": list(_xref_of(subj).get(t) or []),
                        "questions": [],
                    }
    return nodes



