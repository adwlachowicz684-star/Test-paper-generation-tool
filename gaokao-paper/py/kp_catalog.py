def topics_at(subject, l1, l2, include_cross=True):
    """某小知识点下的题型**节点**列表（不再返回裸字符串）"""
    out = [nd for nd in TOPICS.values()
           if nd["subject"] == subject and nd["primary"] == (l1, l2)]
    if include_cross:
        extra = [nd for nd in TOPICS.values()
                 if nd["subject"] == subject
                 and l1 in (nd.get("cross") or [])
                 and nd["id"] not in {x["id"] for x in out}]
        out = out + extra
    return out


def link_question(qid, tids):
    """把题目挂到若干题型上（幂等）。

    只改内存索引。持久化由调用方写回 q['topics']。
    """
    for tid in (tids or []):
        nd = TOPICS.get(tid)
        if nd and qid not in nd["questions"]:
            nd["questions"].append(qid)


def unlink_question(qid):
    """把题目从所有题型上摘掉（改标签前先清旧）"""
    for nd in TOPICS.values():
        if qid in nd["questions"]:
            nd["questions"].remove(qid)


def rebuild_qindex(bank):
    """从题库重建 题型→题目 反索引。

    bank: [{'id':..., 'topics':[tid...]}, ...]
    每次加载题库后调一次即可，保证与题目上的标签一致。
    """
    for nd in TOPICS.values():
        nd["questions"] = []
    n = 0
    for q in bank or []:
        qid = q.get("id")
        if not qid:
            continue
        for tid in (q.get("topics") or []):
            if tid in TOPICS:
                TOPICS[tid]["questions"].append(qid)
                n += 1
    return n


def find_topics(subject, name, exact=True):
    """按名字查题型（同名可能属于不同小知识点，返回全部）"""
    out = [nd for nd in TOPICS.values()
           if nd["subject"] == subject
           and (nd["name"] == name if exact else name in nd["name"])]
    return out


def verify_index(bank, rebuild=False):
    """校验「题目 ↔ 题型」双向挂 ID 是否对称。

    这是整套索引的**契约**：
        题目 q['topics'] 里每个 ID，都能在对应题型的 questions 里找到 q['id']
        题型 nd['questions'] 里每个 ID，对应题目的 topics 里都有 nd['id']

    返回 (是否一致, [不一致描述...])。空列表即完全对称。

    rebuild=False（默认）：**直接校验当前内存状态**，不重建。
      这样才查得出「幽灵引用」—— 题型里挂着题库已删的题目ID。
      若先 rebuild，问卷来源被整个覆盖，幽灵就被洗掉了，永远查不出。

    rebuild=True：先重建再校验，只查题目→题型 方向的坏 ID。

    持久化只存单向（题目→题型），questions 是运行时反建，
    理论上不该不一致 —— 但反建出错或手工改过 JSON 就会出问题，
    而这个错误**不报错**，只表现为「按题型筛出的题对不上」。
    """
    if rebuild:
        rebuild_qindex(bank)
    problems = []

    known = set()
    for q in bank or []:
        qid = q.get('id')
        if not qid:
            continue
        known.add(qid)
        for tid in (q.get('topics') or []):
            if tid not in TOPICS:
                problems.append('题目 %s 挂了不存在的题型 %s' % (qid, tid))
            elif qid not in TOPICS[tid]['questions']:
                problems.append('题目 %s → 题型 %s 缺反向引用' % (qid, tid))

    for tid, nd in TOPICS.items():
        for qid in nd['questions']:
            if qid not in known:
                problems.append('题型 %s 引用了不存在的题目 %s' % (tid, qid))

    return (not problems), problems


def topic_label(tid):
    """人类可读：函数与导数 / 导数压轴小题(一) · 数列与导数"""
    nd = TOPICS.get(tid)
    if not nd:
        return tid
    l1, l2 = nd["primary"]
    s = "%s / %s · %s" % (l1, l2, nd["name"])
    if nd.get("cross"):
        s += "  ↔" + "、".join(nd["cross"])
    return s

