def level3(subject, l1, l2, include_cross=True):
    """某科某二级下的三级题型列表

    include_cross=True（默认）：除本小知识点的**原生题型**外，
    还并入从别处**交叉归属**过来的复合题型（由 TOPIC_XREF 驱动）。

    include_cross=False：只要原生题型，用于统计，避免交叉被重复计数。
    """
    own = []
    for a, subs in CATALOG.get(subject, []):
        if a == l1 and isinstance(subs, dict):
            own = list(subs.get(l2) or [])
            break
    if not include_cross or l2 != XSECTION:
        return own
    xr = _xref_of(subject)
    extra = [t for t, tgts in xr.items() if l1 in tgts]
    return own + [t for t in extra if t not in own]


def _xref_of(subject):
    """自动 + 手工的交叉表（手工覆盖自动）"""
    xr = dict(TOPIC_XREF.get(subject) or {})
    xr.update(TOPIC_XREF_MANUAL.get(subject) or {})
    return xr


def topic_owners(subject, topic):
    """某题型属于哪些 (一级, 二级)。复合题型返回多条。

    返回 [(一级, 二级, 是否主归属), ...]，主归属排第一。
    """
    out = []
    for a, subs in CATALOG.get(subject, []):
        if not isinstance(subs, dict):
            continue
        for k, v in subs.items():
            # 跳过「综合与交叉」挂载点：它只是交叉归属的容器，
            # 不是真正的原生出处，否则复合题型会被算两次。
            if k == XSECTION:
                continue
            if topic in (v or []):
                out.append((a, k, True))
    # 交叉归属：主归属里没有的目标一级才追加
    for tgt in _xref_of(subject).get(topic) or []:
        if tgt not in [a for a, _, _ in out]:
            out.append((tgt, XSECTION, False))
    # 主归属优先；同级按一级名排序
    out.sort(key=lambda x: (not x[2], x[0], x[1]))
    return out


def is_cross(subject, topic, l1):
    """该题型在此一级下是否为交叉归属（而非原生）"""
    return l1 in (_xref_of(subject).get(topic) or [])


def has_topics(subject):
    """该科是否已录入三级题型"""
    for _, subs in CATALOG.get(subject, []):
        if isinstance(subs, dict):
            for v in subs.values():
                if v:
                    return True
    return False


def all_terms(subject, include_topics=False):
    """某科全部知识点（一级+二级[+三级]），用于校验与检索

    include_topics 默认 False：题型名太长且高度重复
    （如多个专题都有「新定义」），纳入检索会造成大量误匹配。
    """
    out = []
    for a, subs in CATALOG.get(subject, []):
        out.append(a)
        it = subs.keys() if isinstance(subs, dict) else subs
        out.extend(it)
        if include_topics and isinstance(subs, dict):
            for tops in subs.values():
                out.extend(tops or [])
    return out


def expand(subject, term):
    """把合并词展开成多个标准一级词。命中返回列表，否则返回 None。"""
    t = str(term or '').strip()
    m = SPLIT.get(subject, {})
    if t in m:
        return list(m[t])
    return None


def normalize(subject, term):
    """把一个知识点写法归一到该科标准一级词。

    命中顺序：一级精确 > 二级精确（返回其一级）> 别名 > 原值。
    归一失败时返回原值，由调用方决定是否保留。
    """
    if not term:
        return term
    t = str(term).strip()
    if not t:
        return t

    for a, subs in CATALOG.get(subject, []):
        if t == a:
            return a
        it = subs.keys() if isinstance(subs, dict) else subs
        if t in it:
            return a

    al = ALIASES.get(subject, {})
    if t in al:
        return al[t]
    # 别名里可能是「二级词」的变体，再试一次前缀匹配
    for k, v in al.items():
        if t and (t.startswith(k) or k in t):
            return v
    return t


def normalize_list(subject, terms):
    """批量归一并去重，保持顺序。合并词会被展开成多个。"""
    out, seen = [], set()
    for t in (terms or []):
        ex = expand(subject, t)
        cands = ex if ex else [normalize(subject, t)]
        for n in cands:
            if n and n not in seen:
                seen.add(n)
                out.append(n)
    return out


def is_valid(subject, term):
    """该写法是否属于此科的标准词表"""
    return normalize(subject, term) in set(level1(subject))


def catalog_for_frontend():
    """给前端的完整目录

    children 为 [{name, topics}]，topics 是该小知识点下的题型列表。
    前端据此渲染三级联动：大知识点 → 小知识点 → 题型。
    """
    out = {}
    for subj, pairs in CATALOG.items():
        lst = []
        for a, subs in pairs:
            if isinstance(subs, dict):
                kids = []
                for k, v in subs.items():
                    # 「综合与交叉」是容器，其题型由 level3 动态并入
                    tops = list(v or []) if k != XSECTION else level3(subj, a, k)
                    # 题型是**节点**：带 ID、挂题数，可与题目双向索引
                    nodes, owners = [], {}
                    for t in tops:
                        tid = topic_id(subj, a, k, t)
                        if tid is None:
                            # 交叉过来的题型：主归属不在 (a,k)，按名字回查
                            cands = find_topics(subj, t)
                            tid = cands[0]["id"] if cands else None
                        nodes.append({
                            "id": tid or "", "name": t,
                            "n_qs": len(TOPICS.get(tid, {}).get("questions") or [])
                            if tid else 0,
                            "label": topic_label(tid) if tid else t,
                            "cross": list(TOPICS.get(tid, {}).get("cross") or [])
                            if tid else [],
                        })
                        owners[t] = topic_owners(subj, t) if tid else []
                    kids.append({
                        "name": k,
                        "topics": tops,
                        "nodes": nodes,
                        "owners": owners,
                    })
            else:
                kids = [{"name": k, "topics": [], "owners": {}} for k in subs]
            lst.append({"name": a, "children": kids})
        out[subj] = lst
    return out


