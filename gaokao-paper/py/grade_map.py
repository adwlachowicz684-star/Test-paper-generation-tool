"""知识点 → 年级 映射（参照人教 A 版教学顺序）

设计要点
--------
**这是派生字段，不写回题库。**

题库 463 道题没有任何一道带年级信息。两个选择：

  A. 批量写进 bank.json —— 一次性方便，但自动判断必有错，
     写进去后错误就固化了，人工复核 463 条不现实。
  B. 运行时按知识点派生 —— 改映射立刻生效，错题不污染原始数据。

选 B。

映射精度
--------
**二级（小知识点）优先于一级。** 因为「函数与导数」269 题横跨
高一（函数性质）到高三（导数压轴），只按一级分必然失真。

未命中返回 UNKNOWN，前端显示为「未标注」——
宁可留白，也不要把没把握的题硬塞进某个年级。

科目差异
--------
目前只有数学有内容。物理/化学/生物的教学顺序与数学完全不同
（比如物理高一力学、高二电磁），科目不同映射表不同，
所以按科目分表，未配置的科目一律 UNKNOWN，不拿数学的表去套。
"""

UNKNOWN = '未标注'

GRADES = ['高一', '高二', '高三']

# ---------- 数学 ----------
# 一级兜底：只用于二级没命中时。
# 注意：一级本身跨度大的（如「函数与导数」）这里给的是**最常见的那一段**，
# 具体仍以二级表为准。
_L1_MATH = {
    '集合与逻辑': '高一',
    '不等式':     '高一',
    '函数与导数': '高二',
    '三角函数':   '高一',
    '平面向量':   '高一',
    '立体几何':   '高二',
    '解析几何':   '高二',
    '概率统计':   '高一',
    '计数原理':   '高二',
    '数列':       '高二',
    '复数':       '高二',
    '统计':       '高一',
}

# 二级精确映射：格式 (一级, 二级) -> 年级
_L2_MATH = {
    # ---- 高一：函数入门、基本初等函数 ----
    ('集合与逻辑', '集合运算'):             '高一',
    ('不等式', '基本不等式'):               '高一',
    ('不等式', '不等式选讲'):               '高三',   # 选讲是高三选考内容
    ('函数与导数', '幂指对比较大小'):        '高一',
    ('函数与导数', '对称性与周期性'):        '高一',
    ('函数与导数', '零点与图像交点'):        '高一',
    ('函数与导数', '零点区间与个数'):        '高一',
    ('函数与导数', '复合函数与嵌套函数零点'): '高一',

    # ---- 高二：导数、圆锥曲线 ----
    ('函数与导数', '导数切线与公切线'):      '高二',
    ('函数与导数', '导数含参讨论'):          '高二',
    ('函数与导数', '导数构造函数'):          '高二',
    ('函数与导数', '导数压轴小题(二)'):      '高三',   # 压轴 = 高三综合
    ('解析几何', '离心率'):                 '高二',
    ('解析几何', '轨迹方程'):               '高二',
    ('解析几何', '圆锥曲线小题'):           '高二',
    ('立体几何', '外接球'):                 '高二',
    ('计数原理', '排列组合'):               '高二',
    ('平面向量', '向量小题'):               '高一',
    ('三角函数', '三角函数性质与最值'):      '高一',
    ('三角函数', '解三角形小题(一)'):        '高一',
    ('三角函数', '解三角形小题(二)'):        '高一',
    ('概率统计', '概率小题'):               '高一',
}

# 按科目索引，未配置的科目查不到 → UNKNOWN
_BY_SUBJ = {'数学': (_L1_MATH, _L2_MATH)}


def grade_of(subject, l1, l2=None):
    """按 (一级, 二级) 推断年级。

    命中优先级：
      1. 二级精确映射
      2. 一级兜底
      3. UNKNOWN

    题目自带的 grade 字段由 grade_of_question() 优先处理。
    """
    conf = _BY_SUBJ.get(subject or '')
    if not conf:
        return UNKNOWN
    l1map, l2map = conf

    if l2:
        g = l2map.get((l1, l2))
        if g:
            return g
    return l1map.get(l1) or UNKNOWN


def grade_of_question(q):
    """给一道题定年级。

    **题目自带的 grade 优先**：人工校订时可以覆盖自动推断
    （比如某道导数题实际是高一竞赛题）。
    没自带的才走知识点映射。
    """
    g = str(q.get('grade') or '').strip()
    if g and g != UNKNOWN:
        return g

    l1s = q.get('kp_list') or []
    l2 = (q.get('kp2') or '').strip()

    # 多知识点题：取**最高年级**。
    # 一道同时考「集合+导数」的题，高二学生才做得了，
    # 归到高一会让高二筛选漏掉它。
    best = None
    for l1 in l1s:
        g = grade_of(q.get('subject'), l1, l2 or None)
        if g == UNKNOWN:
            continue
        if best is None or GRADES.index(g) > GRADES.index(best):
            best = g
    return best or UNKNOWN
